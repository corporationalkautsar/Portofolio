<script setup>
import { route } from 'ziggy-js';
import { computed } from 'vue';
import { Head, Link, useForm } from '@inertiajs/vue3';
import { ArrowLeft, ImagePlus, Save } from 'lucide-vue-next';
import AdminCard from '../../../Components/Admin/AdminCard.vue';
import { useI18n } from '../../../composables/useI18n';

const { t } = useI18n();

const props = defineProps({
    project: { type: Object, default: null },
    categories: { type: Array, default: () => [] },
});

const editing = computed(() => Boolean(props.project));

const form = useForm({
    category_id: props.project?.category_id || props.categories[0]?.id || '',
    title: props.project?.title || '',
    slug: props.project?.slug || '',
    description: props.project?.description || '',
    stack: props.project?.stack || '',
    project_url: props.project?.project_url || '',
    year: props.project?.year || new Date().getFullYear(),
    featured: props.project?.featured || false,
    status: props.project?.status || 'published',
    thumbnail: null,
    project_image: null,
});

function submit() {
    if (editing.value) {
        form.put(route('admin.projects.update', props.project.id), {
            forceFormData: true,
        });
    } else {
        form.post(route('admin.projects.store'), { forceFormData: true });
    }
}
</script>

<template>
    <Head><title>{{ $pageTitle }}</title></Head>

    <div class="space-y-8">
        <div class="flex flex-wrap items-end justify-between gap-5">
            <div>
                <p class="eyebrow">{{ t('admin.projects.content') }}</p>
                <h1 class="mt-4 font-display text-3xl font-semibold md:text-4xl">{{ editing ? t('admin.projects.form.edit') : t('admin.projects.form.create') }}</h1>
            </div>
            <Link :href="route('admin.projects.index')" class="inline-flex items-center gap-2 text-xs text-muted transition-colors hover:text-accent">
                <ArrowLeft :size="15" /> {{ t('admin.projects.form.back') }}
            </Link>
        </div>

        <form class="grid gap-6 xl:grid-cols-[1.5fr_1fr]" @submit.prevent="submit">
            <AdminCard :title="t('admin.projects.form.details')">
                <div class="grid gap-5">
                    <div>
                        <label class="label" for="title">{{ t('admin.projects.form.titleRequired') }}</label>
                        <input id="title" v-model="form.title" class="field" type="text" :placeholder="t('admin.projects.form.titlePlaceholder')" />
                        <p v-if="form.errors.title" class="mt-2 text-xs text-red-400">{{ form.errors.title }}</p>
                    </div>

                    <div class="grid gap-5 sm:grid-cols-2">
                        <div>
                            <label class="label" for="category">{{ t('admin.projects.form.categoryRequired') }}</label>
                            <select id="category" v-model="form.category_id" class="field">
                                <option value="" disabled>{{ t('admin.projects.form.categoryPlaceholder') }}</option>
                                <option v-for="category in categories" :key="category.id" :value="category.id">{{ category.name }}</option>
                            </select>
                            <p v-if="form.errors.category_id" class="mt-2 text-xs text-red-400">{{ form.errors.category_id }}</p>
                        </div>
                        <div>
                            <label class="label" for="slug">{{ t('admin.projects.form.slug') }}</label>
                            <input id="slug" v-model="form.slug" class="field" type="text" :placeholder="t('admin.projects.form.autoGenerated')" />
                            <p v-if="form.errors.slug" class="mt-2 text-xs text-red-400">{{ form.errors.slug }}</p>
                        </div>
                    </div>

                    <div>
                        <label class="label" for="description">{{ t('admin.projects.form.descriptionRequired') }}</label>
                        <textarea id="description" v-model="form.description" class="field min-h-40 resize-y" :placeholder="t('admin.projects.form.descriptionPlaceholder')" />
                        <p v-if="form.errors.description" class="mt-2 text-xs text-red-400">{{ form.errors.description }}</p>
                    </div>

                    <div>
                        <label class="label" for="stack">{{ t('admin.projects.form.stack') }}</label>
                        <input id="stack" v-model="form.stack" class="field" type="text" :placeholder="t('admin.projects.form.stackPlaceholder')" />
                        <p class="mt-2 text-[11px] text-muted">{{ t('admin.projects.form.stackHint') }}</p>
                        <p v-if="form.errors.stack" class="mt-2 text-xs text-red-400">{{ form.errors.stack }}</p>
                    </div>

                    <div class="grid gap-5 sm:grid-cols-2">
                        <div>
                            <label class="label" for="year">{{ t('admin.projects.form.yearRequired') }}</label>
                            <input id="year" v-model="form.year" class="field" type="number" min="1990" />
                            <p v-if="form.errors.year" class="mt-2 text-xs text-red-400">{{ form.errors.year }}</p>
                        </div>
                        <div>
                            <label class="label" for="project_url">{{ t('admin.projects.form.projectUrl') }}</label>
                            <input id="project_url" v-model="form.project_url" class="field" type="url" :placeholder="t('admin.projects.form.urlPlaceholder')" />
                            <p v-if="form.errors.project_url" class="mt-2 text-xs text-red-400">{{ form.errors.project_url }}</p>
                        </div>
                    </div>
                </div>
            </AdminCard>

            <div class="space-y-6">
                <AdminCard :title="t('admin.projects.form.media')" :subtitle="t('admin.projects.form.mediaHint')">
                    <div class="space-y-6">
                        <div v-if="project?.thumbnail_url">
                            <p class="label">{{ t('admin.projects.form.currentThumbnail') }}</p>
                            <img :src="project.thumbnail_url" :alt="t('admin.projects.form.currentThumbnail')" class="mt-2 h-28 w-full rounded-lg border border-line object-cover" />
                        </div>
                        <div>
                            <label class="label" for="thumbnail">{{ t('admin.projects.form.thumbnail') }}</label>
                            <input id="thumbnail" class="field file:mr-3 file:rounded-full file:border-0 file:bg-accent file:px-3 file:py-1 file:text-xs file:font-semibold file:text-ink" type="file" accept="image/*" @change="form.thumbnail = $event.target.files[0]" />
                            <p v-if="form.errors.thumbnail" class="mt-2 text-xs text-red-400">{{ form.errors.thumbnail }}</p>
                        </div>

                        <div v-if="project?.project_image_url">
                            <p class="label">{{ t('admin.projects.form.currentDetailImage') }}</p>
                            <img :src="project.project_image_url" :alt="t('admin.projects.form.currentDetailImage')" class="mt-2 h-28 w-full rounded-lg border border-line object-cover" />
                        </div>
                        <div>
                            <label class="label" for="project_image">{{ t('admin.projects.form.detailImage') }}</label>
                            <input id="project_image" class="field file:mr-3 file:rounded-full file:border-0 file:bg-accent file:px-3 file:py-1 file:text-xs file:font-semibold file:text-ink" type="file" accept="image/*" @change="form.project_image = $event.target.files[0]" />
                            <p v-if="form.errors.project_image" class="mt-2 text-xs text-red-400">{{ form.errors.project_image }}</p>
                        </div>
                    </div>
                </AdminCard>

                <AdminCard :title="t('admin.projects.form.publishing')">
                    <div class="space-y-5">
                        <div>
                            <label class="label" for="status">{{ t('common.status') }}</label>
                            <select id="status" v-model="form.status" class="field">
                                <option value="published">{{ t('common.published') }}</option>
                                <option value="draft">{{ t('common.draft') }}</option>
                            </select>
                            <p v-if="form.errors.status" class="mt-2 text-xs text-red-400">{{ form.errors.status }}</p>
                        </div>
                        <label class="flex items-center justify-between rounded-xl border border-line px-4 py-3 text-sm">
                            {{ t('admin.projects.form.featuredProject') }}
                            <input v-model="form.featured" type="checkbox" class="h-4 w-4 accent-accent" />
                        </label>
                    </div>
                </AdminCard>

                <button class="btn btn-primary w-full" type="submit" :disabled="form.processing">
                    <Save :size="15" /> {{ form.processing ? t('common.saving') : editing ? t('common.saveChanges') : t('admin.projects.form.createSubmit') }}
                </button>
                <p v-if="form.hasErrors" class="text-center text-xs text-red-400">{{ t('admin.projects.form.fixFields') }}</p>
            </div>
        </form>
    </div>
</template>
